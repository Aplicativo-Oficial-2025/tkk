require('dotenv').config();
const express = require('express');
const path = require('path');
const createPix = require('./lib/create-pix');
const app = express();
app.use(express.json({limit:'10kb'}));
app.get('/', (req,res)=>res.sendFile(path.join(__dirname,'public','campanha.html')));
app.use(express.static(path.join(__dirname,'public')));
app.post('/api/pix', createPix);
app.listen(process.env.PORT||3000,()=>console.log('Abra http://localhost:'+(process.env.PORT||3000)));
